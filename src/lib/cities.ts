const normalize = (value: string) => value.replace(/-/g, " ").trim().toLowerCase()

export function citiesForState(stateName: string) {
  return (
    Object.entries(CITIES).find(([name]) => normalize(name) === normalize(stateName))?.[1] ?? []
  )
}

type CenterLocation = { town: string; address: string; addressWithUnit: string }

export function isCenterInTown(center: CenterLocation, town: string) {
  const needle = town.toLowerCase()
  return [center.town, center.address, center.addressWithUnit].some((value) =>
    value.toLowerCase().includes(needle)
  )
}

export function townForCenter(center: CenterLocation, stateName: string) {
  const cities = citiesForState(stateName)
  return (
    cities.find((city) => center.town.toLowerCase().includes(city.toLowerCase())) ??
    cities.find((city) => isCenterInTown(center, city)) ??
    null
  )
}
